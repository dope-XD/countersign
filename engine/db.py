"""The store: customers, case store and audit log. Holds scores, tiers, reason codes,
decisions and the public keys of customers' phones. Never raw audio (RED evidence clips are
separate encrypted files).

SQLite in runtime/countersign.db by default; Postgres (e.g. Supabase) when
COUNTERSIGN_DATABASE_URL or DATABASE_URL is set, for a host whose disk is wiped on restart.
Callers write SQLite-style SQL with ? placeholders either way; [_pg] translates it."""

from __future__ import annotations

import contextlib
import json
import re
import sqlite3
import threading
import time
import uuid
from typing import Any

from engine.config import settings

_SCHEMA = """
CREATE TABLE IF NOT EXISTS customers (
  id TEXT PRIMARY KEY, data TEXT NOT NULL, created_at REAL NOT NULL
);
CREATE TABLE IF NOT EXISTS credentials (
  id TEXT PRIMARY KEY, customer_id TEXT NOT NULL, public_key BLOB NOT NULL,
  sign_count INTEGER NOT NULL DEFAULT 0, transports TEXT, device_label TEXT,
  created_at REAL NOT NULL
);
CREATE TABLE IF NOT EXISTS requests (
  id TEXT PRIMARY KEY, customer_id TEXT NOT NULL, channel TEXT NOT NULL, call_id TEXT,
  action TEXT NOT NULL, details TEXT NOT NULL, tier TEXT, policy TEXT NOT NULL,
  status TEXT NOT NULL, created_at REAL NOT NULL, updated_at REAL NOT NULL,
  cooloff_until REAL
);
CREATE TABLE IF NOT EXISTS approvals (
  id TEXT PRIMARY KEY, request_id TEXT NOT NULL, kind TEXT NOT NULL, target_customer TEXT NOT NULL,
  challenge TEXT NOT NULL, summary TEXT NOT NULL, status TEXT NOT NULL,
  created_at REAL NOT NULL, decided_at REAL, credential_id TEXT, nonce TEXT, assertion TEXT
);
CREATE TABLE IF NOT EXISTS cases (
  id TEXT PRIMARY KEY, call_id TEXT, request_id TEXT, customer_id TEXT, channel TEXT NOT NULL,
  opened_at REAL NOT NULL, status TEXT NOT NULL, tier TEXT, reasons TEXT, scores TEXT,
  model_version TEXT, timeline TEXT NOT NULL, clip_path TEXT, clip_expires REAL, outcome TEXT
);
CREATE TABLE IF NOT EXISTS audit (
  id INTEGER PRIMARY KEY AUTOINCREMENT, ts REAL NOT NULL, actor TEXT NOT NULL,
  event TEXT NOT NULL, ref TEXT, detail TEXT
);
CREATE TABLE IF NOT EXISTS reports (
  id TEXT PRIMARY KEY, kind TEXT NOT NULL, case_id TEXT, created_at REAL NOT NULL, payload TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS replay_landmarks (
  hash INTEGER NOT NULL, case_id TEXT NOT NULL, t INTEGER NOT NULL
);
DROP TABLE IF EXISTS replay_hashes;
CREATE INDEX IF NOT EXISTS ix_requests_customer ON requests(customer_id, channel);
CREATE INDEX IF NOT EXISTS ix_approvals_target ON approvals(target_customer, status);
CREATE INDEX IF NOT EXISTS ix_cases_call ON cases(call_id, status);
CREATE INDEX IF NOT EXISTS ix_cases_request ON cases(request_id, status);
CREATE INDEX IF NOT EXISTS ix_audit_ref ON audit(ref);
"""

_JSON_COLS = {"details", "policy", "reasons", "scores", "timeline", "detail", "payload", "summary", "transports", "assertion"}

# columns added after the first release: (table, column, type), applied to older databases
_ADDED = [("approvals", "nonce", "TEXT"), ("approvals", "assertion", "TEXT"), ("credentials", "kind", "TEXT")]


def _pg(sql: str) -> str:
    """SQLite SQL → Postgres: ? placeholders, and the column types that differ (REAL is only
    4 bytes in Postgres, which would round timestamps to minutes)."""
    sql = sql.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    sql = re.sub(r"\bREAL\b", "DOUBLE PRECISION", sql)
    sql = re.sub(r"\bBLOB\b", "BYTEA", sql)
    sql = re.sub(r"\bINTEGER\b", "BIGINT", sql)
    return sql.replace("?", "%s")


class DB:
    def __init__(self, path, url: str = ""):
        self.path = path
        self.url = url
        self._lock = threading.RLock()
        self.IntegrityError: tuple[type[Exception], ...] = (sqlite3.IntegrityError,)
        if url:
            import psycopg  # only the relay needs it (requirements-relay.txt)

            self.IntegrityError = (psycopg.IntegrityError,)
            self._lost = (psycopg.OperationalError, psycopg.InterfaceError)
        self._connect()
        with self._lock:
            if url:
                for stmt in _SCHEMA.split(";"):
                    if stmt.strip():
                        self._run(stmt)
            else:
                self._conn.executescript(_SCHEMA)
            for table, col, typ in _ADDED:
                if col not in self._columns(table):
                    self._run(f"ALTER TABLE {table} ADD COLUMN {col} {typ}")

    def _connect(self) -> None:
        if self.url:
            import psycopg
            from psycopg.rows import dict_row

            # no prepared statements: Supabase's transaction pooler can't keep them
            self._conn = psycopg.connect(self.url, autocommit=True, row_factory=dict_row, prepare_threshold=None)
        else:
            self._conn = sqlite3.connect(self.path, check_same_thread=False, isolation_level=None)
            self._conn.row_factory = sqlite3.Row
            self._conn.execute("PRAGMA journal_mode=WAL")

    def _columns(self, table: str) -> set[str]:
        if self.url:
            rows = self._run("SELECT column_name FROM information_schema.columns WHERE table_name=?", [table], fetch=True)
            return {r["column_name"] for r in rows}
        return {r[1] for r in self._conn.execute(f"PRAGMA table_info({table})")}

    def _run(self, sql: str, args: list[Any] | tuple = (), fetch: bool = False, many: bool = False) -> list:
        """One statement under the lock. Postgres: translated, and retried once on a fresh
        connection if the old one was dropped (poolers close idle connections)."""
        with self._lock:
            if not self.url:
                if many:
                    self._conn.executemany(sql, args)
                    return []
                cur = self._conn.execute(sql, args)
                return cur.fetchall() if fetch else []
            sql = _pg(sql)
            for attempt in (0, 1):
                try:
                    with self._conn.cursor() as cur:
                        if many:
                            cur.executemany(sql, args)
                            return []
                        cur.execute(sql, args)
                        return cur.fetchall() if fetch else []
                except self._lost:
                    if attempt or not self._conn.closed:
                        raise
                    self._connect()
            return []

    def _row(self, r: sqlite3.Row | dict | None) -> dict | None:
        if r is None:
            return None
        d = dict(r)
        for k in _JSON_COLS & d.keys():
            if isinstance(d[k], str):
                with contextlib.suppress(json.JSONDecodeError):
                    d[k] = json.loads(d[k])
        return d

    def _enc(self, data: dict) -> dict:
        return {k: (json.dumps(v) if k in _JSON_COLS and not isinstance(v, str | bytes | None) else v) for k, v in data.items()}

    def insert(self, table: str, data: dict) -> None:
        data = self._enc(data)
        cols = ",".join(data)
        qs = ",".join("?" * len(data))
        self._run(f"INSERT INTO {table} ({cols}) VALUES ({qs})", list(data.values()))

    def update(self, table: str, id_: str, data: dict) -> None:
        data = self._enc(data)
        sets = ",".join(f"{k}=?" for k in data)
        self._run(f"UPDATE {table} SET {sets} WHERE id=?", [*data.values(), id_])

    def get(self, table: str, id_: str) -> dict | None:
        rows = self._run(f"SELECT * FROM {table} WHERE id=?", [id_], fetch=True)
        return self._row(rows[0]) if rows else None

    def query(self, sql: str, args: list[Any] | tuple = ()) -> list[dict]:
        return [self._row(r) for r in self._run(sql, args, fetch=True)]

    def execute(self, sql: str, args: list[Any] | tuple = ()) -> None:
        self._run(sql, args)

    def executemany(self, sql: str, rows: list[tuple]) -> None:
        self._run(sql, rows, many=True)

    def audit(self, actor: str, event: str, ref: str | None = None, **detail) -> None:
        self.insert("audit", {"ts": time.time(), "actor": actor, "event": event, "ref": ref, "detail": detail or None})

    def wipe_world(self) -> None:
        """Demo reset: clears requests, cases, reports. Keeps customers and their phones' keys."""
        for t in ("requests", "approvals", "cases", "reports", "audit", "replay_landmarks"):
            self._run(f"DELETE FROM {t}")


def new_id(prefix: str) -> str:
    return f"{prefix}_{uuid.uuid4().hex[:10]}"


db = DB(settings.runtime_dir / "countersign.db", settings.database_url)
