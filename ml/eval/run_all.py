EVAL = ROOT / "models" / "eval"
START, END = "<!-- generated by python -m ml.eval.run_all: do not edit by hand -->", "<!-- end of generated part -->"
LODO = ["hinglish_calls", "bothbosu", "india_sms"]
NAMES = {
    "hinglish_calls": "Indian Hinglish call lines (ysangam, test split)",
    "bothbosu": "US-style call dialogues (BothBosu, its own test file)",
    "india_sms": "Indian SMS, English/Hindi/Hinglish (india14 test suite)",
    "uci_sms": "UCI SMS Spam + hand-written Hinglish (bolewara)",
    "team_calls": "Our 27 hand-written calls (cue rules were tuned on these)",
    "adversarial": "Our adversarial set (evasion + hard harmless calls)",
}
GATES = {"recall_warn": 0.90, "fp_warn": 0.08, "fp_scam": 0.01}


def git(*args: str) -> str:
    try:
        return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        return "unknown"


def rate(k: int, n: int) -> dict:
    lo, hi = wilson(k, n)
    return {"k": k, "n": n, "rate": round(k / n, 4) if n else None, "ci95": [round(lo, 4), round(hi, 4)]}


def score(levels: list[tuple[int, str]]) -> dict:
    pos = [lv for y, lv in levels if y == 1]
    neg = [lv for y, lv in levels if y == 0]
    return {
        "scams": len(pos),
        "harmless": len(neg),
        "recall_warn": rate(sum(lv in ("warn", "scam") for lv in pos), len(pos)),
        "recall_scam": rate(sum(lv == "scam" for lv in pos), len(pos)),
        "fp_warn": rate(sum(lv in ("warn", "scam") for lv in neg), len(neg)),
        "fp_scam": rate(sum(lv == "scam" for lv in neg), len(neg)),
    }


def levels_three_ways(r: dict, clf: Classifier, cfg: dict | None = None) -> dict[str, str]:
    f = cfg or fusion_config()
    cues = score_text(r["text"])
    p = clf.p_scam(r["text"])
    clf_only = "scam" if p >= f["scam"]["clf_p"] else "warn" if p >= f["warn"]["clf_p"] else "none"
    return {
        "cues": fuse(cues, cfg=cfg).level,
        "classifier": clf_only,
        "fused": analyze_text(r["text"], clf=clf, cfg=cfg).level,
    }


def text_listener(rows: list[dict], clf: Classifier) -> dict:
    by_set: dict[str, dict[str, list]] = defaultdict(lambda: defaultdict(list))
    by_type: dict[str, list] = defaultdict(list)
    by_lang: dict[str, list] = defaultdict(list)
    misses: list[dict] = []
    for r in rows:
        lv = levels_three_ways(r, clf)
        key = r["source"] if r["split"] == "test" else f"{r['source']}_other_lang"
        for k, v in lv.items():
            by_set[key][k].append((r["label"], v))
        if r["split"] == "test":
            by_type[r["type"] if r["label"] else "harmless"].append((r["label"], lv["fused"]))
            by_lang[r["lang"]].append((r["label"], lv["fused"]))
            wrong = (r["label"] == 1 and lv["fused"] not in ("warn", "scam")) or (r["label"] == 0 and lv["fused"] == "scam")
            if wrong and r["source"] in ("adversarial", "team_calls", "india_sms", "hinglish_calls"):
                misses.append({"id": r["id"], "label": r["label"], "level": lv["fused"], "text": r["text"][:140]})
    return {
        "sets": {s: {k: score(v) for k, v in d.items()} for s, d in sorted(by_set.items())},
        "by_type": {t: score(v) for t, v in sorted(by_type.items())},
        "by_lang": {t: score(v) for t, v in sorted(by_lang.items())},
        "misses": misses,
    }


def leave_one_out(all_rows: list[dict]) -> dict:
    out = {}
    for src in LODO:
        clf, rep = listener_clf.train(all_rows, exclude=src)
        cfg, frep = listener_clf.fit_fusion(all_rows, clf, exclude=src)
        test = [r for r in all_rows if r["source"] == src and r["split"] == "test"]
        lv = [(r["label"], analyze_text(r["text"], clf=clf, cfg=cfg).level) for r in test]
        out[src] = score(lv) | {"trained_on": clf.meta["trained_on"], "dev_auc": rep["dev_auc"]}
    return out


def turns(text: str) -> list[str]:
    parts = re.split(r"\b(?:caller|receiver|suspect|innocent)\s*:", text, flags=re.I)
    return [p.strip() for p in parts if p.strip()]


def turns_to_warn(all_rows: list[dict], clf: Classifier) -> dict:
    team = {t["id"]: t for t in json.loads(listener_data.TEAM.read_text(encoding="utf-8"))["transcripts"]}
    calls = []
    for r in all_rows:
        if r["split"] != "test":
            continue
        if r["source"] == "team_calls":
            calls.append((r, team[r["id"].split("/", 1)[1]]["turns"]))
        elif r["source"] == "bothbosu":
            calls.append((r, turns(r["text"])))
    res: dict[str, list] = {"scam": [], "harmless_warned": [], "words_to_warn": []}
    for r, ts in calls:
        c = LiveCall(clf=clf)
        first = None
        words = 0
        for i, t in enumerate(ts, 1):
            words += len(t.split())
            if c.feed(t) in ("warn", "scam") and first is None:
                first = (i, words)
        if r["label"] == 1:
            res["scam"].append(first[0] if first else None)
            if first:
                res["words_to_warn"].append(first[1])
        else:
            res["harmless_warned"].append(first is not None)
    reached = sorted(x for x in res["scam"] if x is not None)

    def med(xs: list) -> float | None:
        return xs[len(xs) // 2] if xs else None

    return {
        "calls": len(calls),
        "scam_calls": len(res["scam"]),
        "scams_reaching_warn": rate(len(reached), len(res["scam"])),
        "median_turns_to_warn": med(reached),
        "median_words_to_warn": med(sorted(res["words_to_warn"])),
        "harmless_ever_warned": rate(sum(res["harmless_warned"]), len(res["harmless_warned"])),
    }


def pct(x: dict) -> str:
    if not x or x["n"] == 0:
        return "–"
    return f"{100 * x['rate']:.1f}% ({x['k']}/{x['n']}; {100 * x['ci95'][0]:.0f}–{100 * x['ci95'][1]:.0f})"


def markdown(m: dict) -> str:
    t = m["text"]
    L = [
        START,
        "",
        f"_Generated {m['generated_at']} on {m['machine']} in {m['seconds']} s · code {m['git']} · model frozen at {m['frozen_at']} · seed {m['seed']}._",
        "",
    ]
    L += ["### Text listener on held-out data", "", "What the phone shows (fused: cues + our classifier). Percentages with Wilson 95% intervals.", ""]
    L += ["| Test set | Scams at warn | Scams at scam | Harmless at warn (false positive) | Harmless at scam (false positive) |", "|---|---|---|---|---|"]
    for s, d in t["sets"].items():
        f = d["fused"]
        L.append(f"| {NAMES.get(s, s.replace('_', ' '))} | {pct(f['recall_warn'])} | {pct(f['recall_scam'])} | {pct(f['fp_warn'])} | {pct(f['fp_scam'])} |")
    L += ["", "**Each layer alone** (scams at warn / harmless at warn):", "", "| Test set | Cues only | Classifier only | Fused |", "|---|---|---|---|"]

    def cell(x: dict) -> str:
        return f"{100 * x['recall_warn']['rate']:.0f}% / {100 * x['fp_warn']['rate']:.0f}%" if x["scams"] and x["harmless"] else "–"

    for s, d in t["sets"].items():
        L.append(f"| {NAMES.get(s, s)} | {cell(d['cues'])} | {cell(d['classifier'])} | {cell(d['fused'])} |")
    if m.get("lodo"):
        L += [
            "",
            "### Leave one dataset out (never seen in train or dev)",
            "",
            "| Held-out source | Trained on | Scams at warn | Harmless at warn | Harmless at scam |",
            "|---|---|---|---|---|",
        ]
        for s, d in m["lodo"].items():
            L.append(f"| {NAMES.get(s, s)} | {', '.join(d['trained_on'])} | {pct(d['recall_warn'])} | {pct(d['fp_warn'])} | {pct(d['fp_scam'])} |")
    L += ["", "### Per scam type (all held-out sets, fused)", "", "| Type | Texts | Reached warn | Reached scam |", "|---|---|---|---|"]
    for ty, d in t["by_type"].items():
        if ty == "harmless":
            L.append(f"| harmless | {d['harmless']} | {pct(d['fp_warn'])} (false positive) | {pct(d['fp_scam'])} (false positive) |")
        else:
            L.append(f"| {ty} | {d['scams']} | {pct(d['recall_warn'])} | {pct(d['recall_scam'])} |")
    L += ["", "### Per language (all held-out sets, fused)", "", "| Language | Scams at warn | Harmless at warn | Harmless at scam |", "|---|---|---|---|"]
    for lg, d in t["by_lang"].items():
        L.append(f"| {lg} | {pct(d['recall_warn'])} | {pct(d['fp_warn'])} | {pct(d['fp_scam'])} |")
    tw = m.get("turns_to_warn")
    if tw:
        L += ["", "### Turns to warn on multi-turn calls (BothBosu test + our calls, fed turn by turn)", ""]
        L += [
            f"- Scam calls reaching warn: {pct(tw['scams_reaching_warn'])}; median {tw['median_turns_to_warn']} turns, {tw['median_words_to_warn']} words in."
        ]
        L += [f"- Harmless calls that ever showed warn: {pct(tw['harmless_ever_warned'])}."]
    g = m["gates"]
    L += ["", "### Gates (set before the test run)", ""]
    for k, v in g.items():
        L.append(f"- {k}: {v}")
    runs = {
        "audio": "ml.eval.asr_bakeoff",
        "voice": "ml.voice_clone && python -m ml.voice_calibrate",
        "kit": "ml.eval.kit data/kit --basic --json models/eval/kit.json",
    }
    titles = {
        "audio": "Audio end to end (on-phone speech-to-text → listener), the speech-to-text bake-off",
        "voice": "Voice-clone model (on the phone; held-out sets, scored with the shipped int8 model)",
        "kit": "Spot-check kit (data/kit: 30 public held-out items; the same files on the phone's Check a recording)",
    }
    for sec in ("audio", "voice", "kit"):
        L += ["", f"### {titles[sec]}", ""]
        L += [m[sec].get("markdown", "_see models/metrics.json_")] if m.get(sec) else [f"_Not run on this machine yet (`python -m {runs[sec]}`)._"]
    if t["misses"]:
        L += [
            "",
            "### Every miss on our own and the Indian sets (scam below warn, or harmless at scam)",
            "",
            "| Id | Truth | Phone said | Text (start) |",
            "|---|---|---|---|",
        ]
        for x in t["misses"][:60]:
            L.append(f"| {x['id']} | {'scam' if x['label'] else 'harmless'} | {x['level']} | {x['text'].replace('|', '/')} |")
    L += ["", END]
    return "\n".join(L)


def check_gates(m: dict) -> dict:
    # the gates are about the Indian held-out sets the app is for; every set is still reported above
    pool = [m["text"]["sets"][s]["fused"] for s in ("hinglish_calls", "india_sms", "adversarial") if s in m["text"]["sets"]]
    k = lambda key, part: sum(p[key][part] for p in pool)  # noqa: E731
    rw = k("recall_warn", "k") / max(1, k("recall_warn", "n"))
    fw = k("fp_warn", "k") / max(1, k("fp_warn", "n"))
    fs = k("fp_scam", "k") / max(1, k("fp_scam", "n"))
    audio = (m.get("audio") or {}).get("models", {}).get("omnilingual_300m", {}).get("channels", {})
    line = {}
    for ch in ("clean", "g711u", "ota+g711u"):
        r = (audio.get(ch) or {}).get("scams_at_warn")
        if r and r["n"]:
            line[f"audio, {ch}: scams at warn ≥ 80%"] = f"{100 * r['rate']:.0f}% → {'met' if r['rate'] >= 0.8 else 'MISSED'}"
    return line | {
        "scams at warn ≥ 90% (Indian held-out sets pooled)": f"{100 * rw:.1f}% → {'met' if rw >= GATES['recall_warn'] else 'MISSED'}",
        "harmless at warn ≤ 8%": f"{100 * fw:.1f}% → {'met' if fw <= GATES['fp_warn'] else 'MISSED'}",
        "harmless at scam ≤ 1%": f"{100 * fs:.1f}% → {'met' if fs <= GATES['fp_scam'] else 'MISSED'}",
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    a = ap.parse_args()
    t0 = time.time()
    rows = listener_data.load()
    test = [r for r in rows if r["split"] in ("test", "test_other_lang")]
    if a.quick:
        rng = random.Random(listener_data.SEED)
        uci = [r for r in test if r["source"] == "uci_sms"]
        keep = {r["id"] for r in rng.sample(uci, min(600, len(uci)))}
        test = [r for r in test if r["source"] != "uci_sms" or r["id"] in keep]
    clf = classifier()
    m: dict = {
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "git": git("rev-parse", "--short", "HEAD"),
        "frozen_at": git("log", "-1", "--format=%h %cI", "--", str(ASSETS / "scam_clf.bin"), str(ASSETS / "fusion.json")),
        "seed": listener_data.SEED,
        "machine": f"{platform.system()} {platform.machine()}, Python {platform.python_version()}",
        "quick": a.quick,
        "data": listener_data.table(rows),
        "classifier": {k: v for k, v in clf.meta.items() if k != "about"},
        "fusion": fusion_config(),
    }
    print("text listener …", file=sys.stderr)
    m["text"] = text_listener(test, clf)
    print("turns to warn …", file=sys.stderr)
    m["turns_to_warn"] = turns_to_warn(rows, clf)
    if not a.quick:
        print("leave one dataset out …", file=sys.stderr)
        with tempfile.TemporaryDirectory():
            m["lodo"] = leave_one_out(rows)
    for sec, name in (("audio", "asr_bakeoff.json"), ("voice", "voice_clone.json"), ("kit", "kit.json")):
        if (EVAL / name).exists():
            m[sec] = json.loads((EVAL / name).read_text(encoding="utf-8"))
    for d in (m.get("voice") or {}).get("sets", {}).values():  # per-clip scores stay in voice_clone.json
        d.pop("scores_real", None)
        d.pop("scores_ai", None)
    m.get("audio", {}).pop("examples", None)
    m["gates"] = check_gates(m)
    m["seconds"] = round(time.time() - t0, 1)
    old = json.loads(METRICS.read_text(encoding="utf-8")) if METRICS.exists() else {}
    if "benchmarks" in old:
        m["laptop_s1_legacy"] = {"note": "The old laptop voice model (cut from the demo path); kept for PLAN_VS_BUILT.", "benchmarks": old["benchmarks"]}
    elif "laptop_s1_legacy" in old:
        m["laptop_s1_legacy"] = old["laptop_s1_legacy"]
    METRICS.write_text(json.dumps(m, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    md = markdown(m)
    if RESULTS.exists() and START in RESULTS.read_text(encoding="utf-8"):
        doc = RESULTS.read_text(encoding="utf-8")
        doc = doc[: doc.index(START)] + md + doc[doc.index(END) + len(END) :]
    else:
        doc = "# Results\n\n" + md + "\n"
    RESULTS.write_text(doc, encoding="utf-8")
    print(md)
    print(f"\nwrote {METRICS.relative_to(ROOT)} and {RESULTS.relative_to(ROOT)} in {m['seconds']} s", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
