"""Every number in docs/RESULTS.md, from public data, on any OS with a CPU. The test workflow is part of the submission.

    python -m ml.eval.run_all            # ~3 minutes: text listener (+ leave-one-dataset-out), audio and voice if present
    python -m ml.eval.run_all --quick    # ~1 minute: no leave-one-dataset-out, UCI SMS sampled to 600

Steps:
  1. Fetch the public text sets (ml.listener_data; ~7 MB from Hugging Face) and build the seeded splits.
  2. Text listener on every held-out set, three ways: cues only, classifier only, and fused (what the phone shows).
     For each: share of scams reaching warn and scam, share of harmless texts reaching warn and scam (false
     positives), with Wilson 95% intervals; then per scam type and per language.
  3. Leave one dataset out: retrain without a source (its train and dev too), refit fusion on the rest's dev,
     test on that source's test split. This is how well it generalises to a kind of data it has never seen.
  4. Turns to warn on multi-turn calls: how many caller/receiver turns before the card turns amber.
  5. Audio end to end (models/eval/asr_bakeoff.json from ml.eval.asr_bakeoff) and the voice-clone model
     (models/eval/voice_clone.json from ml.eval.voice_clone), copied in if those runs exist.
  6. Write models/metrics.json (served at /api/metrics) and the generated part of docs/RESULTS.md, with the data,
     seed, versions, the commit the model was frozen at and the runtime.

The classifier and the fusion thresholds were fitted on train/dev only (ml.listener_clf) and frozen in git before
this runs; `frozen_at` is the last commit that changed them.
"""

